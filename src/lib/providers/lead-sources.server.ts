/**
 * Pluggable Lead Source architecture.
 *
 * Add a new source by implementing LeadSource and registering it below.
 * Nothing in the UI or database is coupled to a specific provider.
 */
import type { LeadSearchRequest, ProviderDescriptor, RawLead } from "@/lib/domain-types";
import { ProviderNotConfiguredError, ProviderUnavailableError } from "./runtime.server";
import {
  SELF_HOSTED_GMAPS_ID,
  isConfigured as gmapsConfigured,
  searchSelfHostedGoogleMaps,
} from "./self-hosted-google-maps.server";

export interface LeadSource {
  id: string;
  name: string;
  description: string;
  capabilities: string[];
  estimatedCostPerUnit?: number | null;
  configurationHint?: string;
  isConfigured(): boolean;
  search(request: LeadSearchRequest): Promise<RawLead[]>;
}

/**
 * Self-hosted open-source Google Maps discovery.
 *
 * The scraper (gosom/google-maps-scraper, MIT) runs as a separate service you
 * deploy yourself; this adapter only calls its HTTP API server-side.
 */
import { getRuntimeConfig } from "@/lib/config/runtime-config.server";

const selfHostedGoogleMaps: LeadSource = {
  id: SELF_HOSTED_GMAPS_ID,
  name: "Google Maps — Server Scraper (Render)",
  description:
    "Queries your own self-hosted google-maps-scraper service for publicly listed business data.",
  capabilities: [
    "business search",
    "location filter",
    "category filter",
    "public phone",
    "rating & reviews",
  ],
  // Self-hosted: no per-result vendor fee, only your own infrastructure cost.
  estimatedCostPerUnit: 0,
  configurationHint:
    "Deploy the scraper container, then add the GMAPS_SCRAPER_URL secret (plus GMAPS_SCRAPER_API_KEY if your deployment requires one).",
  isConfigured() {
    return gmapsConfigured();
  },
  search: searchSelfHostedGoogleMaps,
};

